#!/usr/bin/env python3
"""Pack a four level PNG into the table the panic face draws.

    tests/tools/img2gray4.py assets/panic.png payload/panicimage.h

The screen that carries a panic report is read from a photograph of the
machine, and the report is a few lines of text: the picture above it is a sign
saying what happened rather than something to be looked at closely. Four
levels are what such a sign is drawn in, and they are a quarter of what a byte
a pixel would cost in a blob that is copied whole.

The picture has to be in the levels already, and this only packs it. Which
four levels a picture should come out in is a decision about the picture, and
the one place it can be made is with the picture in front of the reader --
gray4.py, beside the other working copies of the pictures, is where that is
done. A tool that quantised whatever it was given would pack an eight bit
picture that merely looks quantised as if it were one, and the result would be
the wrong quarter of it.

Two bits a pixel, four to a byte with the left pixel in the highest bits, and
a row after another. The drawer expands a level by multiplying it by 85, so
that the levels come out as 0, 85, 170 and 255.

Generated once and committed, like the font, so that a build needs nothing but
this tree.
"""
import sys

# Four levels, two bits a pixel, which is what the drawer draws and the whole
# of what it draws: the two sides have to agree about this and nothing else
BITS = 2
LEVELS = 1 << BITS
VALUES = tuple(level * (255 // (LEVELS - 1)) for level in range(LEVELS))


def levelsOf(image):
    """The picture as level numbers, one a pixel, left to right and top down."""
    gray = image.convert("L").tobytes()
    other = set(gray) - set(VALUES)

    if other:
        raise SystemExit(
            "the picture holds %s, and this packs the %d levels %s: quantise "
            "it first, which assets_generation/gray4.py does"
            % (sorted(other)[:4], LEVELS, list(VALUES)))
    return [VALUES.index(value) for value in gray]


def packed(levels):
    """Levels into bytes, the left pixel of a run in the highest bits."""
    per = 8 // BITS
    out = []

    for at in range(0, len(levels), per):
        byte = 0

        for i, level in enumerate(levels[at:at + per]):
            byte |= level << (8 - BITS * (i + 1))
        out.append(byte)
    return out


def header(width, height, data, source):
    out = []
    out.append("/*")
    out.append(" * The picture the panic face draws, as levels")
    out.append(" *")
    out.append(" * Generated by tests/tools/img2gray4.py from %s." % source)
    out.append(" * Committed rather than generated at build time so that a build needs")
    out.append(" * nothing but this tree")
    out.append(" *")
    out.append(" * Four levels, two bits a pixel, four to a byte and the left pixel of a")
    out.append(" * run in the highest bits, one row after another. The drawer expands a")
    out.append(" * level by multiplying it by 85, so 0 is black and 255 white. This file")
    out.append(" * is not meant to be edited")
    out.append(" */")
    out.append("")
    out.append("#ifndef US_PANIC_IMAGE_H")
    out.append("#define US_PANIC_IMAGE_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("#define US_PANIC_IMAGE_WIDTH %d" % width)
    out.append("#define US_PANIC_IMAGE_HEIGHT %d" % height)
    out.append("")
    out.append("static const uint8_t kPanicImage[%d] = {" % len(data))
    for at in range(0, len(data), 16):
        cells = ", ".join("0x%02x" % value for value in data[at:at + 16])
        out.append("    %s," % cells)
    out.append("};")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: img2gray4.py <in.png> <out.h>")
    source, target = sys.argv[1], sys.argv[2]
    try:
        from PIL import Image
    except ImportError:
        raise SystemExit("reading a PNG needs Pillow: pip install pillow")

    image = Image.open(source)
    width, height = image.size
    # A row has to be a whole number of bytes, or the row below starts halfway
    # through a byte and every pixel after it is read from the wrong place
    if (width * BITS) % 8 != 0:
        raise SystemExit("%d pixels a row is not a whole number of bytes at "
                         "%d bits a pixel" % (width, BITS))
    data = packed(levelsOf(image))
    with open(target, "w") as f:
        f.write(header(width, height, data, source))
    print("wrote %s: %dx%d, %d bytes" % (target, width, height, len(data)))


if __name__ == "__main__":
    main()
